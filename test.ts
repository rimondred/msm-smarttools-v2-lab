// Projet de compilation : anciennes API + surface générale Lot 3.
function verifierApiLot3(): void {
    msmSmartTools.initialiserDaDabit()
    msmSmartTools.configurerPropulsion(msmSmartTools.ProfilPropulsion.QuatreRouesP9P10)
    msmSmartTools.faireTournerActionneur(1, 50)
    msmSmartTools.arreterActionneur(1)
    msmSmartTools.positionnerActionneur(6, 20, 500)
    msmSmartTools.actionnerPuisRevenir(6, 20, 0, 1000)
    msmSmartTools.avancer(55)
    msmSmartTools.reculer(55)
    msmSmartTools.tournerAGauche(44)
    msmSmartTools.tournerADroite(44)
    msmSmartTools.arreterRobot()
    msmSmartTools.avancerPendant(55, 500)
    msmSmartTools.reculerPendant(55, 500)
    msmSmartTools.tournerPendant(msmSmartTools.Direction.Gauche, 44, 500)

    let etat = msmSmartTools.lireEtatLigne()
    etat = msmSmartTools.lireEtatLigneFiltre(5)
    let oui = msmSmartTools.capteurSurNoir(msmSmartTools.CapteurLigne.S2)
    oui = msmSmartTools.intersectionDetectee()
    oui = msmSmartTools.lignePerdue()
    msmSmartTools.suivreLigne(55)
    oui = msmSmartTools.suivreJusquaIntersection(55, 5000)
    oui = msmSmartTools.quitterIntersection(msmSmartTools.Direction.Droite, 44, 3000)

    msmSmartTools.activerVision(msmSmartTools.ModeVision.Couleur)
    msmSmartTools.mettreAJourCamera()
    oui = msmSmartTools.couleurDetectee(1)
    etat = msmSmartTools.positionCouleur(1, msmSmartTools.AxeVision.X)
    oui = msmSmartTools.couleurStable(1, 8)
    msmSmartTools.activerVision(msmSmartTools.ModeVision.Visage)
    oui = msmSmartTools.visageDetecte()
    etat = msmSmartTools.xVisage()
    oui = msmSmartTools.visageStable(5)
    msmSmartTools.activerVision(msmSmartTools.ModeVision.Landmark)
    etat = msmSmartTools.landmarkReconnu()
    etat = msmSmartTools.confianceLandmark()
    oui = msmSmartTools.landmarkDetecte(1)
    oui = msmSmartTools.landmarkStable(1, 8)
    msmSmartTools.activerVision(msmSmartTools.ModeVision.Classification)
    etat = msmSmartTools.classeReconnue()
    etat = msmSmartTools.confianceClassification()
    oui = msmSmartTools.classeDetectee(2)
    oui = msmSmartTools.classeStable(2, 8)
    oui = msmSmartTools.attendreDetectionStable(msmSmartTools.ModeVision.Nombre, 1, 8, 5000)

    msmSmartTools.configurerCanauxBrasPince(5, 6)
    msmSmartTools.configurerBras3Axes(1, 2, 3, 1500)
    msmSmartTools.configurerPoseBras3Axes(msmSmartTools.PoseBras3Axes.Repos, -90, 45, -135)
    msmSmartTools.deplacerBras3Axes(0, 90, -135, 1500)
    msmSmartTools.allerPoseBras3Axes(msmSmartTools.PoseBras3Axes.Repos)
    msmSmartTools.saisirObjet()
    msmSmartTools.deposerObjet()
    msmSmartTools.allumerLEDs(msmSmartTools.CouleurLED.Bleu)
    msmSmartTools.afficherEtat(msmSmartTools.EtatAffiche.Succes)
}
